"""牌型规则段：听牌 / 成牌 / 空气 / 成牌+有效听牌，四类互斥注入。

牌型分类描述牌况，不决定行动许可；成牌只有真实听花或听顺才归入 combo，
其他改善 outs 不触发 combo 分类，牌力质量与行动阈值另行判断。

牌型段只写「这手牌靠什么赢 + 默认动作」；人数/位置/短码/河牌修正留在
`scenario.py`，场景段按 hand_class 只渲染对应口径。
"""

from __future__ import annotations

from ...hand_track import PREFLOP

DRAW_RULES = """## 牌型：听牌
- 主要靠兑现权益赢：下注/加注=半诈唬；跟注看范围权益、价格、隐含赔率和线路。
- 默认过牌；但攻击口径满足（该尺寸「他弃」≥「需要」）且单挑/3 人池、有位置或强听时，1/3–1/2 池半诈唬是标准线，不要求每个对手都有 ≥50% 实测。大注/连开两街才要「L2+ 且每个仍能行动的对手实测 ≥50%」；3 人以上门槛更高。纯听不主动做大池。
- 被加注、身后仍有人能加注或 outs 有被统治风险时，隐含赔率/outs 打折；短码按即时赔率。
- 中花/中顺前看牌面结构：公对面/成花面/顺子可能时按非坚果处理；被跟后不因「没中」继续投入。"""

# 成牌段共用的正文。combo 额外多一条「有牌又有听」，避免把纯听牌的默认过牌
# 套到成牌身上；跟注口径也分开：纯成牌没有隐含赔率，combo 的听牌部分有。
_MADE_COMMON = """- 靠摊牌/价值赢：下注/加注=价值（先问更差的牌会不会跟）；没有更差的牌会跟就过牌。
  价值分档：强价值=两对+/三条+（可以打光/大注）；可下注价值=强价值+超对+顶对强踢；薄价值=顶对/超对里偏弱的一档。
  顶对强踢=顶对且踢脚 ≥J。对手是跟注型（跟 c-bet ≥55%、河牌跟得多）且范围里你赢的够多时，薄价值也下注；「不是坚果」不是过牌理由。
- 抓诈不是价值档：弱对/公对只在有诈唬证据时跟注，不主动做大池。
- 多人池（≥4 人）：顶对/超对降级；两对+打光前先看公对面和更大的两对；
  无位置默认过牌控池，两对+例外；被加注非坚果时，不默认把三条街都打满；河牌只看当前街。
- 牌面：成花/公对/公三条/顺子可能 → 默认不能当坚果；若「坚果」事实为「是」，以事实为准；公对面葫芦风险；
  公顺/公花时踢脚不参与比牌。"""

_MADE_CALL = """- 跟注：默认按当前权益对门槛（成牌没有隐含赔率）；set/两对/三条在翻牌/转牌、深码、对手范围偏价值时可用隐含赔率修正，但要有出路（公对面/成花面要打折）。低于门槛就弃，「接近」不是跟注理由。
  人多或身后还有人能加注要收紧；被加注看「对手加注范围的构成」（成牌/听牌/空气），不只看权益。"""

_COMBO_CALL = """- 跟注：范围权益对门槛，听花/听顺部分可用隐含赔率修正（被加注时按剩余牌算）。
  人多或身后还有人能加注要收紧；被加注看「对手加注范围的构成」，不只看权益。"""

MADE_RULES = "## 牌型：成牌\n" + _MADE_COMMON + "\n" + _MADE_CALL

COMBO_RULES = ("## 牌型：成牌+有效听牌（有牌又有听）\n"
               "- 当前已有摊牌价值且有真实听花或听顺；只有这两类补牌听牌归 combo（如中对听花/顺），不要求 ≥8 outs。\n"
               "- 分类不等于强牌/下注许可：分开评估更差牌跟注的价值、弃牌收益、被跟后的权益、被加注后的继续能力；低质量/被统治 outs 折价。\n"
               "- 相比纯成牌可因保护/半诈唬/后续权益增加下注理由；诈唬按攻击口径（该尺寸他弃 ≥ 需要），没有 EV 依据时不能仅凭有听牌就开火。\n"
               + _MADE_COMMON + "\n" + _COMBO_CALL)

AIR_RULES = """## 牌型：空气
- 当前无成牌、无真实听花/听顺：默认过牌/弃牌；若只有高张/其他反超 outs，仍按空气评估，不把它们当听牌权益。
- 纯空气也看 EV：1/3–1/2 池在「他弃 ≥ 需要 + 10pt」、单挑/3 人池、有位置、牌面有利时可以开一枪；大注/连续多街才要「L3 + 每个对手 ≥50% 实测」。只有类型标签或先验时不禁止小注，但不要拿它开大注。
- 河牌没有摊牌价值时只剩有证据的诈唬或弃牌：他弃 ≥ 该尺寸需要就诈唬（优先小注），否则弃；不要把高张反超 outs 当成成牌权益。"""


def hand_type_section(sit) -> str | None:
    """按 `sit.hand_class` 返回唯一一段牌型规则；翻前/牌不全时不注入。"""
    if sit.snap.street == PREFLOP or sit.ground_truth is None:
        return None
    cls = sit.hand_class
    if cls == "draw":
        return DRAW_RULES
    if cls == "combo":
        return COMBO_RULES
    if cls == "made":
        return MADE_RULES
    return AIR_RULES
